$word = New-Object -ComObject Word.Application
$word.Visible = $false
$word.DisplayAlerts = 0

function Rep($doc, $find, $repl) {
  $f = $doc.Content.Find
  $f.ClearFormatting()
  $f.Replacement.ClearFormatting()
  $ok = $f.Execute($find, $false, $false, $false, $false, $false, $true, 1, $false, $repl, 2)
  $shown = if ($find.Length -gt 45) { $find.Substring(0, 45) + '…' } else { $find }
  Write-Output ('   [{0}] {1}' -f $(if ($ok) { ' ok ' } else { 'НЕТ' }), $shown)
}

function Make-Blank($src, $dst, $pairs) {
  $srcPath = Join-Path $root $src
  $dstPath = Join-Path $root $dst
  Copy-Item $srcPath $dstPath -Force
  $doc = $word.Documents.Open($dstPath)
  Write-Output ('=== ' + $dst)
  foreach ($p in $pairs) { Rep $doc $p[0] $p[1] }
  $doc.Save()
  $doc.Close(0)
}

